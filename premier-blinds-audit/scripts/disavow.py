"""Write Google disavow files: one per owned Search Console property.
- premierblindsanddesigns.com = money site = FULL UNION of every Spam (Disavow) domain.
- thepremierdesigns.com = redirect property = domains whose links point at it.
Held domains are NEVER written. domain: lines, grouped by reason, with a header.
"""
import os, sys
from collections import defaultdict
from datetime import date
sys.path.insert(0, os.path.dirname(__file__))
import pipeline
OUT = os.path.join(os.path.dirname(__file__), "..", "out")

REASON_GROUP = {
    "PBN sales-copy anchor": "Link-scheme / PBN sales-copy anchors",
    "Spam host name": "Known spam / link-network host names",
    "Spam page title / URL template": "Spam / autogenerated page titles or URL templates",
    "Off-topic anchor": "Off-topic (unrelated) anchors",
}

HEADER = """# Google Disavow file  -  {client}
# Property: {prop}
# Generated: {today}  by Harbinger Marketing (backlink audit)
# Domains in this file: {count}
#
# WHAT THIS IS: referring domains confirmed as spam, each with at least one
# dofollow link. Every line rests on visible evidence (a spam anchor, a spam
# page title/URL, or a known link-network host) - never on Authority Score,
# TLD or IP alone.
#
# HELD LINKS ARE EXCLUDED. {held} domains carry exact-match commercial anchors
# or point at deep product/service pages and may have been commissioned
# placements. They are NOT in this file. The client must first confirm with the
# previous SEO provider (the party that ran prior link building) whether any
# were paid for. Do NOT add held domains until that conversation happens.
#
# DO NOT UPLOAD THIS FILE until the held-link conversation above is complete.
# We did not submit anything to Google Search Console - the client uploads this.
# We have NOT confirmed whether a disavow file already exists on this property.
#   If one already exists, uploading this REPLACES it entirely - merge the two
#   lists first. If the client has checked and there is none, this is the first.
{union}#
"""

UNION_NOTE = ("# This is the MONEY-SITE file: it carries the COMPLETE UNION of every bad\n"
              "#   domain, including those reaching the site through the thepremierdesigns.com\n"
              "#   301 redirect, because Google forwards disavow signals across a redirect\n"
              "#   imperfectly. Listing a domain that does not link here directly is harmless.\n")

def write_file(prop, domains_dict, dom_list, held_count, is_union):
    groups = defaultdict(list)
    for d in dom_list:
        reason = domains_dict[d]["reason"]
        groups[REASON_GROUP.get(reason, "Other spam evidence")].append(d)
    lines = [HEADER.format(client="Premier Blinds & Designs", prop=prop,
                           today=date.today().isoformat(), count=len(dom_list),
                           held=held_count, union=(UNION_NOTE if is_union else ""))]
    for grp in sorted(groups):
        lines.append("\n# --- %s (%d) ---" % (grp, len(groups[grp])))
        for d in sorted(groups[grp]):
            lines.append("domain:%s" % d)
    path = os.path.join(OUT, "disavow_%s.txt" % prop)
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    return path, len(dom_list)

def main():
    ds = pipeline.build()
    domains = ds["domains"]
    emitted = ds["emitted"]                     # disavow domains, redundant children removed
    held = sum(1 for v in domains.values() if v["status"].startswith("Held"))

    # money-site union file
    p1, n1 = write_file("premierblindsanddesigns.com", domains, emitted, held, is_union=True)
    # thepremierdesigns.com attribution file
    tpd = [d for d in emitted if "thepremierdesigns.com" in domains[d]["properties"]]
    p2, n2 = write_file("thepremierdesigns.com", domains, tpd, held, is_union=False)

    print("UNION  %s : %d domains" % (os.path.basename(p1), n1))
    print("REDIR  %s : %d domains (links attributed to thepremierdesigns.com)" % (os.path.basename(p2), n2))
    # property breakdown
    pb = {}
    for d in emitted:
        for pr in domains[d]["properties"]:
            pb[pr] = pb.get(pr,0)+1
    print("attribution across properties (emitted disavow domains):")
    for pr,n in sorted(pb.items(), key=lambda x:-x[1]):
        print("   %-40s %d" % (pr, n))

if __name__ == "__main__":
    main()
