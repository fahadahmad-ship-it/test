def _any(patterns, text):
    return any(re.search(p, text) for p in patterns)

def has_product(a):   return _any(PRODUCT, a)
def has_geo(a):       return _any(GEO, a)

def anchor_type(anchor):
    a = (anchor or "").strip().lower()
    if a == "" or a in ("-", "image", "img"):
        return "Empty or image"
    if _any(PBN, a):
        return "Spam: keyword stuffed SEO sales copy"
    if _any(OFFTOPIC, a):
        return "Spam: off topic"
    # naked URL: anchor is essentially a bare domain/url
    if a.startswith("http") or re.fullmatch(r"(www\.)?[a-z0-9.-]+\.[a-z]{2,}/?", a) \
       or any(o in a and len(a) <= len(o) + 8 for o in OWNED):
        return "Naked URL"
    if _any(BRAND, a):
        return "Branded"
    if has_product(a):
        return "Exact match commercial (geo)" if has_geo(a) else "Exact match commercial"
    if _any(GENERIC, a):
        return "Generic"
    return "Contextual or other"

SPAM_ANCHOR_TYPES = {"Spam: keyword stuffed SEO sales copy", "Spam: off topic"}
EXACT_TYPES = {"Exact match commercial", "Exact match commercial (geo)"}

def is_deep_page(target_url):
    """True if the link points at a deep money page (not the home page)."""
    u = (target_url or "").lower().split("?")[0]
    m = re.search(r"https?://[^/]+(/.*)?$", u)
    path = m.group(1) if (m and m.group(1)) else "/"
    path = path.rstrip("/")
    return path not in ("", "/")

def classify_domain(dom, links, ascore):
    """links: list of dicts with keys anchor,target_url,nofollow,source_url,source_title.
    Returns (status, reason). ascore: float referring-domain Authority Score."""
    root = dom.lower()
    if root in OWNED:
        return "Own Site", "Client-owned / redirect domain"

    types = [anchor_type(l["anchor"]) for l in links]
    has_dofollow = any(l["nofollow"].strip().lower() == "false" for l in links)
    has_pbn = any(t == "Spam: keyword stuffed SEO sales copy" for t in types)
    has_off = any(t == "Spam: off topic" for t in types)
    has_exact = any(t in EXACT_TYPES for t in types)
    has_deep = any(is_deep_page(l["target_url"]) for l in links)
    host_spam = _any(SPAM_HOST, root)
    title_spam = any(_any(SPAM_TITLE, (l["source_title"] or "").lower())
                     or _any(SPAM_URL, (l["source_url"] or "").lower()) for l in links)
    is_press = _any(PRESS, root)
    # benign citation: a linking page title that names the client w/o sales copy
    benign_cite = any(
        (MONEY_SITE.split(".")[0] in (l["source_title"] or "").lower()
         or "premier blinds" in (l["source_title"] or "").lower())
        and not _any(SPAM_TITLE, (l["source_title"] or "").lower())
        and not _any(PBN, (l["anchor"] or "").lower())
        for l in links)

    commercial_signal = has_exact or has_deep

    def split(base):
        if base == "Spam":
            return "Spam (Disavow)" if has_dofollow else "Spam (Nofollow, No Action)"
        if base == "Held":
            return "Held (Pending Partner)" if has_dofollow else "Held (Nofollow, No Action)"
        return base

    # Verdict order (first match wins)
    # 1. off-topic is always spam, never rescued
    if has_off and not commercial_signal:
        return split("Spam"), "Off-topic anchor"
    # 2. exact-match AND PBN on same domain -> Held (may be a paid placement)
    if has_pbn and commercial_signal:
        return split("Held"), "Exact-match/deep-page + PBN mix (possible paid placement)"
    # 3. pure PBN sales copy -> Spam
    if has_pbn:
        return split("Spam"), "PBN sales-copy anchor"
    if has_off:
        return split("Spam"), "Off-topic anchor"
    # 4. exact-match commercial anchor -> Held (a money anchor may be a paid placement
    #    even from an otherwise genuine-looking host)
    if has_exact:
        return split("Held"), "Exact-match commercial anchor"
    # 5. genuine authority (before the bare deep-page rule, so real high-AS
    #    directories with a generic/branded anchor are kept, not held)
    if ascore is not None and ascore >= 20:
        return "Keep", "Authority Score >= 20 (genuine site)"
    # 6. link to a deep money page (non-commercial anchor) -> Held (scheme targets deep pages)
    if has_deep:
        return split("Held"), "Link to deep money page"
    # 7. press release syndication -> Held
    if is_press:
        return split("Held"), "Press-release syndication host"
    # 8. benign citation naming the client
    if benign_cite:
        return "Keep", "Linking page names the client, no sales copy"
    # 9. spam host name
    if host_spam:
        return split("Spam"), "Spam host name"
    # 10. spam page title / url template
    if title_spam:
        return split("Spam"), "Spam page title / URL template"
    # 11. otherwise
    return "Keep", "No spam evidence"
