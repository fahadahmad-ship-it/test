"""Generate the 7 Summary key findings from the classified data.
Usage: python3 -I compute_findings.py <classified.json> <out findings_text.py>
Numbers only from the data; verifier re-derives them.
"""
import sys, os, json, collections
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common as C

data = json.load(open(sys.argv[1], encoding="utf-8"))
n = len(data)
by = collections.Counter(r["status"] for r in data)
spam_dis = by.get("Spam (Disavow)", 0)
spam_nf = by.get("Spam (Nofollow, No Action)", 0)
spam_total = spam_dis + spam_nf
held = by.get("Held (Pending Partner)", 0) + by.get("Held (Nofollow, No Action)", 0)

# link-level home vs deep
home = deep = 0
pbn_links = 0
for r in data:
    for l in r["links"]:
        if C.is_home(l["target_url"]):
            home += 1
        else:
            deep += 1
        if l.get("anchor_type") == "Spam: keyword stuffed SEO sales copy":
            pbn_links += 1

# dominant anchor: top anchor text + how many referring domains use it
anc_dom = collections.defaultdict(set)
for r in data:
    for l in r["links"]:
        a = (l.get("anchor") or "").strip()
        if a:
            anc_dom[a].add(r["domain"])
top_anchor, top_doms = max(anc_dom.items(), key=lambda kv: len(kv[1]))

# held with no traffic
held_recs = [r for r in data if r["status"].startswith("Held")]
held_notraffic = sum(1 for r in held_recs if not r.get("traffic"))

# IP /24 networks among non-CDN
cl = collections.Counter()
for r in data:
    ip = r.get("ip", "")
    if ip and not C.is_cdn_ip(ip):
        s = C.slash24(ip)
        if s:
            cl[s] += 1
net = {s: c for s, c in cl.items() if c >= 5}
net_domains = sum(c for c in net.values())

F = []
F.append(f"{spam_total:,} of the {n:,} referring domains are spam. {spam_dis:,} have at least one "
         f"dofollow link and go in the disavow file; the other {spam_nf:,} are nofollow and need no action.")
F.append(f"The attack is far larger than the brief. erthproducts.com went from a ~75 referring-domain "
         f"baseline (spring 2026) to ~1,003 live domains now (Semrush counts {n:,} across its history); "
         f"the brief's \"207 since June\" was a stale snapshot, so we audited the full live profile.")
F.append(f"You can upload one disavow file, for erthproducts.com. No owned domains redirect into the site "
         f"(the Semrush redirect column is empty), so that single file covers the whole property.")
F.append(f"Two patterns, easy to tell apart. {home:,} links hit the home page (the link-scheme flood); "
         f"{deep:,} hit deep product pages (the commissioned-looking campaign). The home-page flood is the "
         f"attack; the product-page links may have been commissioned and are held.")
F.append(f"The single biggest anchor, on {len(top_doms):,} referring domains, is SEO sales copy that names "
         f"the client's own domain: “{top_anchor[:70]}…”.")
F.append(f"{held:,} domains are held for the partner who commissioned the links to confirm, in case any were "
         f"paid placements. {len(net)} non-CDN /24 IP ranges each host 5+ of the referring domains "
         f"({net_domains:,} domains in total), a sign of shared link-network hosting rather than independent sites.")
F.append(f"Held does not mean valuable: {held_notraffic:,} of the {held:,} held domains have no Semrush organic "
         f"traffic at all. None should be treated as a genuine endorsement until the partner confirms it.")

with open(sys.argv[2], "w", encoding="utf-8") as fh:
    fh.write("# Auto-generated by compute_findings.py — numbers derived from the audit data.\n")
    fh.write("FINDINGS = [\n")
    for s in F:
        fh.write("    " + repr(s) + ",\n")
    fh.write("]\n")
print(f"wrote {len(F)} findings")
for s in F:
    print(" -", s[:110])
